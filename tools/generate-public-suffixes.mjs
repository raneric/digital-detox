// Regenerates src/background/public-suffixes.js from the Public Suffix List.
// Run from the repo root: node tools/generate-public-suffixes.mjs
// Keeps the ICANN section only (single-label plain rules are dropped — the
// matcher treats the last label as a suffix by default).

import { readFileSync, writeFileSync } from 'fs';

const URL_ = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUT = new URL('../src/background/public-suffixes.js', import.meta.url);

const dat = await (await fetch(URL_)).text();
const lines = dat.split('\n').map((l) => l.trim());

// ICANN section runs from BEGIN ICANN DOMAINS to BEGIN PRIVATE DOMAINS.
let inIcann = false;
const rules = [];
for (const line of lines) {
  if (line.startsWith('// ===BEGIN ICANN DOMAINS===')) { inIcann = true; continue; }
  if (line.startsWith('// ===END ICANN DOMAINS===')) { inIcann = false; continue; }
  if (!inIcann || !line || line.startsWith('//')) continue;
  const rule = line.split(/\s+/)[0].toLowerCase();
  if (!rule) continue;
  if (rule.startsWith('!')) rules.push({ type: 'exception', suffix: rule.slice(1) });
  else if (rule.startsWith('*.')) rules.push({ type: 'wildcard', suffix: rule.slice(2) });
  else rules.push({ type: 'plain', suffix: rule });
}

// Single-label plain rules (com, uk, ...) are covered by the matcher's
// default; wildcard and exception rules must be kept regardless of length.
const multi = rules.filter((r) => r.type !== 'plain' || r.suffix.includes('.'));
const exceptions = multi.filter((r) => r.type === 'exception').map((r) => r.suffix).sort();
const wildcards = multi.filter((r) => r.type === 'wildcard').map((r) => r.suffix).sort();
const plain = multi.filter((r) => r.type === 'plain').map((r) => r.suffix).sort();

const body = `/**
 * Multi-label public suffixes from the ICANN section of the Public Suffix List
 * (https://publicsuffix.org/list/public_suffix_list.dat, MPL-2.0).
 * The private section (github.io, s3.amazonaws.com, ...) is intentionally not
 * included — the extension manages social-media domains, which are all ICANN.
 * Single-label suffixes (com, org, uk, ...) are not listed; the matcher
 * treats the last label as a suffix by default.
 *
 * Generated by tools/generate-public-suffixes.mjs — do not edit by hand.
 */

/** @type {string[]} Full multi-label public suffixes (e.g. "co.uk"). */
export const PLAIN = ${JSON.stringify(plain)};

/** @type {string[]} Wildcard rule bases: "*.<base>" is a public suffix. */
export const WILDCARD = ${JSON.stringify(wildcards)};

/** @type {string[]} Exception rules: "<suffix>" is registrable, not a suffix. */
export const EXCEPTION = ${JSON.stringify(exceptions)};
`;

writeFileSync(OUT, body);
console.log(`plain=${plain.length} wildcard=${wildcards.length} exception=${exceptions.length} -> ${OUT.pathname}`);